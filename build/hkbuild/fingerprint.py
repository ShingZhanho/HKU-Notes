"""Content fingerprints independent of checkout location and file timestamps."""
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import sys

from pathspec import GitIgnoreSpec
from .metadata import REPOSITORY


def file_hash(path):
    with path.open('rb') as handle:
        return hashlib.file_digest(handle, 'sha256').hexdigest()


def generated_outputs(root, spec):
    paths = set(spec.get('outputs', {}).values())
    if spec.get('output_file'):
        paths.add(spec['output_file'])
    if spec.get('root_file'):
        paths.add(str(Path(spec['root_file']).with_suffix('.pdf')))
    for step in [*spec.get('prepare', []), *spec.get('steps', []), *spec.get('finish', [])]:
        paths.update(step.get('outputs', []))
        if step['type'] == 'wordcount':
            paths.add(step['output'])
        if step['type'] == 'latex':
            for pattern in step['inputs']:
                paths.update(str(p.relative_to(root).with_suffix('.pdf')) for p in root.glob(pattern))
    return paths


def source_files(root, spec):
    defaults = (REPOSITORY / 'build/hash-ignore-defaults.txt').read_text().splitlines()
    ignore = GitIgnoreSpec.from_lines([*defaults, *spec.get('hash_ignore', [])])
    outputs = generated_outputs(root, spec)
    entries = []
    for directory, dirs, files in os.walk(root):
        # Build caches and Git administrative data are never source inputs.
        dirs[:] = sorted(name for name in dirs if name not in ('.git', '.build'))
        for name in sorted(files):
            path = Path(directory) / name
            relative = path.relative_to(root).as_posix()
            if relative == 'metadata.json':
                pass  # Metadata cannot be excluded, even by '*' or a default pattern.
            elif relative in outputs or ignore.match_file(relative):
                continue
            elif name == 'Makefile' and path.read_bytes().startswith(b'# Generated by HKU Notes configure.'):
                continue
            if not path.resolve().is_relative_to(root.resolve()):
                raise ValueError(f'Hash input escapes source root: {path}')
            entries.append((relative, path.stat().st_mode & 0o111, file_hash(path)))
    return sorted(entries)


def fingerprint(document, spec, profile=None, source_override=None):
    # Hash the raw metadata separately as well: an override directory never replaces
    # the document's build definition, and broad ignore rules cannot hide edits to it.
    inputs = {'document': source_files(document, spec)}
    if source_override:
        override = Path(source_override).resolve()
        if not override.is_dir():
            raise ValueError(f'Source directory does not exist: {override}')
        inputs['override'] = source_files(override, spec)
    # Pinned remote sources are identified by the full source declaration in spec.
    # Their internal .build checkout is a cache, not an editable source override.
    tooling = [*sorted((REPOSITORY / 'build/hkbuild').glob('*.py')),
               *sorted((REPOSITORY / 'build/python-requirement-lists').glob('*.txt')),
               REPOSITORY / 'build/build.py', REPOSITORY / 'configure',
               REPOSITORY / 'build/hash-ignore-defaults.txt',
               REPOSITORY / 'build/bootstrap-ubuntu.sh', REPOSITORY / 'build/setup-miktex.sh',
               REPOSITORY / 'site/docs/statics/schemas/v3.json']
    packages = {}
    for package in spec.get('requires', {}).get('python', []):
        try:
            packages[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            packages[package] = None
    data = {'version': 1, 'metadata': file_hash(document / 'metadata.json'),
            'spec': spec, 'profile': profile, 'inputs': inputs,
            'tooling': [(str(p.relative_to(REPOSITORY)), file_hash(p)) for p in tooling],
            'environment': [platform.system(), platform.machine(), list(sys.version_info[:2]), packages]}
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()
