"""Generate small GNU Make frontends for the common build runner."""
import argparse
import json
from pathlib import Path
import shlex
import shutil
import sys
from urllib.parse import urlparse

from .document import check_tools, write_json
from .metadata import REPOSITORY, load, resolve_alias
from .targets import select

MARKER = '# Generated by HKU Notes configure. Do not edit.\n'


def shell(value):
    # Shell quoting and Make escaping are separate layers.
    return shlex.quote(str(value)).replace('$', '$$')


def generate(config, config_path):
    command = ' '.join(shell(value) for value in [sys.executable, REPOSITORY / 'build/build.py', '--config', config_path])
    build_command = command + ' $(if $(filter 1,$(FORCE)),--force,)'
    lines = [MARKER, '.DEFAULT_GOAL := all\n', 'FORCE ?= 0\n', '.PHONY: all site preview clean distclean help ' + ' '.join(config['targets']) + '\n']
    if config['mode'] == 'document':
        lines += [f'all:\n\t{build_command} build\n', f'preview: all\n\t{command} preview\n', f'site:\n\t{command} site\n']
    else:
        lines.append('all: ' + ' '.join(config['targets']) + '\n')
        for target in config['targets']:
            canonical = resolve_alias(Path(config['repository']) / 'src' / target).name
            if canonical != target:
                lines.append(f'{target}: {canonical}\n')
            else:
                lines.append(f'{target}:\n\t{build_command} build {shell(target)}\n')
        lines += [f'preview: all\n\t{command} preview\n', f'site: preview\n\t{command} site\n']
    lines += [f'clean:\n\t{command} clean\n', f'distclean:\n\t{command} distclean\n',
              'help:\n\t@echo "all: compile; preview: HTML pages; site: website (repository mode); clean: auxiliaries; distclean: generated outputs and configuration"\n']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Configure local document or website builds (Python 3.11+, GNU Make).')
    parser.add_argument('--targets', nargs='+', help='Repository target selection; default: build/build-targets.txt')
    parser.add_argument('--profile', help='Document build profile')
    parser.add_argument('--source-dir', type=Path, help='Document source override (already at the selected subdirectory)')
    parser.add_argument('--artifact-dir', type=Path, help='Use existing <target>/<output> artifacts where present')
    parser.add_argument('--site-url', default='https://hku.jacobshing.com/', help='Canonical URL for generated site and sitemaps')
    parser.add_argument('--no-check', action='store_true', help='Defer tool/environment checks until make')
    args = parser.parse_args(argv)
    if urlparse(args.site_url).scheme not in ("http", "https") or not urlparse(args.site_url).netloc:
        parser.error("--site-url must be an absolute http(s) URL")
    directory = Path.cwd().resolve()
    document_mode = (directory / 'metadata.json').is_file()
    if not document_mode and directory != REPOSITORY:
        parser.error('Run configure from a document root containing metadata.json or from the repository root')
    if document_mode and args.targets:
        parser.error('--targets is only available at the repository root')
    if not document_mode and (args.profile or args.source_dir):
        parser.error('--profile and --source-dir are document options')
    targets = [directory.name] if document_mode else select(REPOSITORY, args.targets)
    if document_mode:
        resolve_alias(directory)
    for target in targets:
        document = resolve_alias(directory if document_mode else REPOSITORY / 'src' / target)
        spec = load(document / 'metadata.json', args.profile)['build']
        supplied = args.artifact_dir and (args.artifact_dir / document.name).is_dir()
        if not args.no_check and not supplied:
            check_tools(document, spec, args.source_dir)
    if not args.no_check and not shutil.which('make'):
        parser.error('GNU Make is required')
    makefile = directory / 'Makefile'
    if makefile.exists() and not makefile.read_text().startswith(MARKER):
        parser.error(f'Refusing to overwrite a hand-written {makefile}')
    config = {'version': 1, 'mode': 'document' if document_mode else 'repository',
              'repository': str(REPOSITORY), 'directory': str(directory), 'targets': targets,
              'profile': args.profile, 'source_dir': str(args.source_dir.resolve()) if args.source_dir else None,
              'artifact_input': str(args.artifact_dir.resolve()) if args.artifact_dir else None,
              'site_url': args.site_url,
              'artifact_root': str(directory / '.build/artifacts' if document_mode else REPOSITORY / 'dist/artifacts')}
    path = directory / '.build/config.json'
    write_json(path, config)
    makefile.write_text(generate(config, path), encoding='utf-8')
    print(f'Configured {", ".join(targets)}\nPython: {sys.executable}\nArtifacts: {config["artifact_root"]}\nRun make to build' + ('; make site to build the website.' if not document_mode else '.'))
